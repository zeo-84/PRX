var SkillLearnerPrompt = {
    labels: {
        currentLevel: { "absolute-beginner": "Absolute Beginner", beginner: "Beginner", intermediate: "Intermediate", advanced: "Advanced" },
        learningGoal: { "career-change": "Career Change", "project-based": "Build a Project", hobby: "Hobby", freelance: "Freelancing" },
        timeline: { "1-month": "1 Month", "3-months": "3 Months", "6-months": "6 Months" }
    },
    label: function(field, value) {
        return (this.labels[field] && this.labels[field][value]) || value || "N/A";
    },
    getWeeks: function(timeline) {
        var map = { "1-month": 4, "3-months": 12, "6-months": 24 };
        return map[timeline] || 12;
    },
    generate: function(data) {
        var weeks = this.getWeeks(data.timeline);
        return [
            "# PERSONALIZED LEARNING PATH",
            "# Skill: " + data.skillName,
            "",
            "---",
            "",
            "## LEARNER PROFILE",
            "",
            "- **Skill:** " + data.skillName,
            "- **Current Level:** " + this.label("currentLevel", data.currentLevel),
            "- **Goal:** " + this.label("learningGoal", data.learningGoal),
            "- **Daily Time:** " + data.dailyTime + " minutes/day",
            "- **Timeline:** " + this.label("timeline", data.timeline) + " (~" + weeks + " weeks)",
            "",
            "---",
            "",
            "## EXISTING KNOWLEDGE",
            "",
            data.prerequisites || "None specified - assuming complete beginner",
            "",
            "---",
            "",
            "## CHALLENGES",
            "",
            data.challenges || "None specified",
            "",
            "---",
            "",
            "## LEARNING ROADMAP",
            "",
            "You are an expert educator. Create a detailed week-by-week learning plan.",
            "",
            "### For each week, provide:",
            "1. **Week Title** - Clear focus area",
            "2. **Learning Objectives** - 3-5 specific goals",
            "3. **Topics to Cover** - Detailed concepts",
            "4. **Recommended Resources** - Specific courses, books, articles",
            "5. **Practice Exercises** - Hands-on activities",
            "6. **Mini Project** - Apply what was learned",
            "7. **Self-Assessment** - How to verify understanding",
            "",
            "### Progression Rules:",
            "- Start from current level (do not repeat known material)",
            "- Each week builds on previous",
            "- Review sessions every 3-4 weeks",
            "- Balance theory (30%) with practice (70%)",
            "- Real-world projects by week 3-4",
            "",
            "---",
            "",
            "## MILESTONES",
            "",
            "- Week 2: Foundation check",
            "- Week " + Math.ceil(weeks * 0.33) + ": First major milestone",
            "- Week " + Math.ceil(weeks * 0.66) + ": Intermediate milestone",
            "- Week " + weeks + ": Final assessment",
            "",
            "---",
            "",
            "## FINAL PROJECT",
            "",
            "Design a capstone project that combines all learned skills and can be added to a portfolio.",
            "",
            "---",
            "",
            "Make the plan actionable, specific, and encouraging. Use a friendly, motivating tone."
        ].join("\n");
    }
};