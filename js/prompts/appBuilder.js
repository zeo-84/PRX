var AppBuilderPrompt = {
    labels: {
        projectType: { web: "Web Application", mobile: "Mobile App", fullstack: "Full-Stack App", api: "REST API", landing: "Landing Page", dashboard: "Admin Dashboard", ecommerce: "E-Commerce Store", saas: "SaaS Platform" },
        frontendFramework: { react: "React", nextjs: "Next.js", vue: "Vue.js", angular: "Angular", svelte: "Svelte", vanilla: "Vanilla HTML/CSS/JS" },
        backendFramework: { "node-express": "Node.js + Express", django: "Django", fastapi: "FastAPI", laravel: "Laravel", none: "No Backend" },
        database: { postgresql: "PostgreSQL", mongodb: "MongoDB", mysql: "MySQL", firebase: "Firebase", none: "No Database" },
        language: { typescript: "TypeScript", javascript: "JavaScript", python: "Python" },
        complexity: { simple: "Simple (MVP)", medium: "Medium", complex: "Complex (Enterprise)" },
        designStyle: { modern: "Modern & Clean", minimal: "Minimalist", glassmorphism: "Glassmorphism", dark: "Dark Theme", material: "Material Design" }
    },
    featureLabels: {
        auth: "User Authentication & Authorization",
        database: "Database Integration & ORM",
        api: "REST / GraphQL API",
        payment: "Payment Processing (Stripe/PayPal)",
        realtime: "Real-time Features (WebSockets)",
        search: "Search & Filter Functionality",
        notifications: "Push / In-app Notifications",
        testing: "Unit & E2E Testing"
    },
    label: function(field, value) {
        return (this.labels[field] && this.labels[field][value]) || value || "N/A";
    },
    generate: function(data) {
        var features = data.features.length > 0
            ? data.features.map(function(f) { return "  - " + (AppBuilderPrompt.featureLabels[f] || f); }).join("\n")
            : "  - (No specific features selected)";

        var pages = data.pages
            ? data.pages.split("\n").filter(function(p) { return p.trim(); }).map(function(p) { return "  - " + p.trim(); }).join("\n")
            : "  - (Not specified)";

        return [
            "# COMPREHENSIVE APP DEVELOPMENT PROMPT",
            "# Project: " + data.projectName,
            "",
            "---",
            "",
            "## PROJECT OVERVIEW",
            "",
            "You are an expert full-stack developer. Build the following application with production-quality code.",
            "",
            "**Project Name:** " + data.projectName,
            "**Project Type:** " + this.label("projectType", data.projectType),
            "**Complexity:** " + this.label("complexity", data.complexity),
            "",
            "---",
            "",
            "## TECHNICAL STACK",
            "",
            "- **Frontend:** " + (data.frontendFramework ? this.label("frontendFramework", data.frontendFramework) : "Not specified"),
            "- **Backend:** " + (data.backendFramework ? this.label("backendFramework", data.backendFramework) : "Not specified"),
            "- **Database:** " + (data.database ? this.label("database", data.database) : "Not specified"),
            "- **Language:** " + this.label("language", data.language),
            "",
            "---",
            "",
            "## DESIGN",
            "",
            "- **Style:** " + this.label("designStyle", data.designStyle),
            "- **Responsive:** Yes, fully responsive",
            "- **Accessibility:** WCAG 2.1 AA compliant",
            "",
            "---",
            "",
            "## PROJECT DESCRIPTION",
            "",
            data.description || "(No description provided)",
            "",
            "---",
            "",
            "## REQUIRED FEATURES",
            "",
            features,
            "",
            "---",
            "",
            "## PAGES / ROUTES",
            "",
            pages,
            "",
            "---",
            "",
            "## DEVELOPMENT GUIDELINES",
            "",
            "### Architecture",
            "- Use modular, component-based architecture",
            "- Follow SOLID principles",
            "- Proper folder structure (feature-based)",
            "",
            "### Code Quality",
            "- Clean, readable, self-documenting code",
            "- Meaningful variable names",
            "- JSDoc comments for complex functions",
            "- DRY principle",
            "",
            "### Security",
            "- Sanitize all user inputs",
            "- Parameterized queries",
            "- Proper auth and authorization",
            "- Protect against XSS, CSRF, SQL injection",
            "",
            "### Testing",
            "- Unit tests for business logic",
            "- Integration tests for APIs",
            "- Minimum 70% coverage",
            "",
            "---",
            "",
            "## DELIVERABLES",
            "",
            "1. Complete, runnable source code",
            "2. package.json with all dependencies",
            "3. .env.example file",
            "4. README.md with setup instructions",
            "5. Database schema (if applicable)",
            "",
            "---",
            "",
            "## ADDITIONAL NOTES",
            "",
            data.additionalNotes || "None",
            "",
            "---",
            "",
            "Start by outlining the project structure, then implement each component systematically."
        ].join("\n");
    }
};